async function initializeSubtitles() {
  if ((window as any).__bundaiSubtitleInit) {
    return
  }
  ;(window as any).__bundaiSubtitleInit = true

  if (subtitleContainer) {
    subtitleContainer.destroy()
  }

  subtitleContainer = new YouTubeSubtitleContainer()

  if (initialEnabled === null) {
    initialEnabled = (subtitleContainer as any).isEnabled
  }

  console.log("[YouTube Subtitles] Subtitle system initialized")
}

if (typeof chrome !== "undefined" && chrome.runtime) {
  const getCurrentVideoId = () => {
    try {
      const url = window.location.href || ""
      const match =
        url.match(/(?:youtube\.com\/watch\?v=|youtu\.be\/)([^&?/]+)/i) ||
        url.match(/youtube\.com\/watch.*?[?&]v=([^&?/]+)/i)
      return match?.[1] || null
    } catch {
      return null
    }
  }

  chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
    if (message.action === "setExtensionEnabled") {
      const newEnabled = message.enabled
      const wasEnabled = (subtitleContainer as any)?.isEnabled

      if (subtitleContainer) {
        subtitleContainer.setEnabled(newEnabled)
      }

      sendResponse({ success: true })
      return true
    }

    if (message.action === "setWordCardStyles") {
      if (subtitleContainer) {
        ;(subtitleContainer as any).wordCardStyles = message.styles || {}
        if (typeof (subtitleContainer as any).renderWordCard === "function") {
          ;(subtitleContainer as any).renderWordCard()
        }
      }
      sendResponse({ success: true })
      return true
    }

    if (message.action === "setSubtitleContainerStyles") {
      if (subtitleContainer) {
        ;(subtitleContainer as any).subtitleContainerStyles =
          message.styles || {}
        if (
          typeof (subtitleContainer as any).reapplySubtitleStyles === "function"
        ) {
          ;(subtitleContainer as any).reapplySubtitleStyles()
        }
      }
      sendResponse({ success: true })
      return true
    }

    if (message.action === "getExtensionState") {
      if (subtitleContainer) {
        sendResponse({ enabled: (subtitleContainer as any).isEnabled })
      } else {
        sendResponse({ enabled: false })
      }
      return true
    }

    if (message.action === "checkStatus") {
      const hasContainer = !!document.getElementById("bundai-subtitle-root")
      sendResponse({
        isEnabled: (subtitleContainer as any)?.isEnabled || false,
        hasContainer: hasContainer,
        videoElement: !!(subtitleContainer as any)?.videoElement
      })
      return true
    }

    if (message.action === "getPlaybackState") {
      sendResponse({
        success: true,
        currentTime: (subtitleContainer as any)?.videoElement?.currentTime || 0,
        paused: (subtitleContainer as any)?.videoElement?.paused ?? true
      })
      return true
    }

    if (message.action === "getUseAutoGeneratedSubtitles") {
      sendResponse({ useAutoGenerated: false })
      return true
    }

    if (message.action === "loadAsrSubtitle") {
      const cues = Array.isArray(message.cues) ? message.cues : []
      const targetVideoId =
        typeof message.videoId === "string" ? message.videoId : null
      const currentVideoId = getCurrentVideoId()

      if (targetVideoId && currentVideoId && targetVideoId !== currentVideoId) {
        sendResponse({
          success: false,
          ignored: true,
          reason: "video_id_mismatch",
          currentVideoId
        })
        return true
      }

      const enCues = Array.isArray(message.enCues) ? message.enCues : []

      if (subtitleContainer) {
        const sc = subtitleContainer as any
        if (sc.subtitle1Element && sc.subtitle2Element) {
          sc.subtitle1Data = cues
          sc.lastProcessedSubtitle1Text = ""
          sc.subtitle2Data = enCues
          sc.lastProcessedSubtitle2Text = ""
        } else {
          sc.pendingAsrCues = cues
          sc.pendingEnCues = enCues
        }
      }

      sendResponse({ success: true, loaded: cues.length, enLoaded: enCues.length })
      return true
    }

    if (message.action === "clearAsrSubtitle") {
      const targetVideoId =
        typeof message.videoId === "string" ? message.videoId : null
      const currentVideoId = getCurrentVideoId()

      if (targetVideoId && currentVideoId && targetVideoId !== currentVideoId) {
        sendResponse({
          success: false,
          ignored: true,
          reason: "video_id_mismatch",
          currentVideoId
        })
        return true
      }

      if (subtitleContainer) {
        ;(subtitleContainer as any).subtitle1Data = []
        ;(subtitleContainer as any).lastProcessedSubtitle1Text = ""
        ;(subtitleContainer as any).subtitle2Data = []
        ;(subtitleContainer as any).lastProcessedSubtitle2Text = ""
      }

      sendResponse({ success: true })
      return true
    }

    if (message.action === "updateAllTabs") {
      if (subtitleContainer) {
        const newEnabled = message.enabled
        ;(subtitleContainer as any).isEnabled = newEnabled
        if (newEnabled) {
          ;(subtitleContainer as any).init()
        } else {
          ;(subtitleContainer as any).removeSubtitleContainer()
        }
      }
      sendResponse({ success: true })
      return true
    }
  })
}

