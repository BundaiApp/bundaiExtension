  private onYouTubeNavigation(): void {
    const newVideoId = this.extractVideoId(window.location.href)

    if (!newVideoId) return

    if (this.currentVideoId && this.currentVideoId !== newVideoId) {
      console.log(
        `[YouTube Subtitles] Navigation detected: ${this.currentVideoId} → ${newVideoId}`
      )
      this.currentVideoId = newVideoId
      this.removeSubtitleContainer()
      this.videoElement = null
      this.subtitleGeneration++
      this.autoGeneratedSubtitles = []

      if (this.navTimeout) clearTimeout(this.navTimeout)
      this.navTimeout = setTimeout(() => {
        this.navTimeout = null
        if (this.isEnabled) {
          this.findAndSetupVideo()
          if (!this.videoElement) {
            this.observeForVideo()
          }
        }
      }, 800)
    } else if (!this.currentVideoId) {
      this.currentVideoId = newVideoId
    }
  }

